export function getListingById(id: number): Listing | undefined {
  return listings.find((l) => l.id === id);
}

export function getByActivity(activity: ActivityType): Listing[] {
  return listings.filter((l) => l.activities.includes(activity));
}

export function getByBoatCategory(category: string): Listing[] {
  return listings.filter((l) => l.boatCategory === category);
}

export function getFeatured(): Listing[] {
  return listings.filter(
    (l) => l.rating.score > 0 || l.thirdPartyReviews || l.activities.length >= 6
  );
}

export function getAffordable(): Listing[] {
  return [...listings].sort((a, b) => a.minPrice.value - b.minPrice.value).slice(0, 6);
}

export function getPremium(): Listing[] {
  return [...listings].sort((a, b) => b.minPrice.value - a.minPrice.value).slice(0, 6);
}
